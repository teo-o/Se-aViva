    public static string Path(string name) =>
        Paths.TryGetValue(name, out var path) ? path : throw new ArgumentException($"Unknown pixel icon '{name}'.", nameof(name));

    private static string ToPath(string[] rows)
    {
        var path = new StringBuilder();
        for (var y = 0; y < rows.Length; y++)
        {
            var row = rows[y];
            for (var x = 0; x < row.Length; x++)
            {
                if (row[x] != '#')
                {
                    continue;
                }

                var start = x;
                while (x + 1 < row.Length && row[x + 1] == '#')
                {
                    x++;
                }

                path.Append($"M{start} {y}h{x - start + 1}v1h-{x - start + 1}z");
            }
        }

        return path.ToString();
    }
}
